#!/usr/bin/env python3
"""Exact certificate for the marked unramified class term at ``p = 23``.

At the literal ordinary conductor ``r = 11, a = 1`` the paper isolates an
odd character ``Theta = omega * theta^-1`` of conductor ``23 * 363`` whose
generalized Bernoulli value has exact 23-adic valuation one.  This script
certifies the remaining marked-prime statement without a class-group
completeness assumption.

For

    epsilon = product_(a in (Z/363 Z)^x)
                (1 - zeta_363^a)^(theta(a)^-1 mod 23),

it checks two independent facts.

* In the degree-22 unramified 23-adic completion, represented modulo 23^2 by

      (Z/529 Z)[T] / (T^22 + 255 T^11 + 487),

  epsilon is a 23rd power.  Thus adjoining its 23rd root after adjoining
  ``mu_23`` is unramified above 23 (and it is automatically unramified away
  from 23 because epsilon is a global unit).

* In the exact binary field

      F_2[X] / (X^110 + X^33 + 1),

  the 23rd-power residue symbol of epsilon is ``zeta_23^4 != 1``.  Hence the
  Kummer extension is nontrivial and its Frobenius at every prime over 2 is
  nontrivial after descent to the degree-22 field cut out by ``Theta``.

All polynomial arithmetic is implemented with the Python standard library.
The computation is a finite certificate for this one actual Conway
conductor, not a proof of the universal ordinary arm.
"""

from __future__ import annotations

import math

if not __debug__:
    raise SystemExit("assertions must remain enabled; do not run with python -O")


P = 23
P2 = P * P
CONDUCTOR = 363
DEGREE = 22
FULL_CONDUCTOR = P * CONDUCTOR


def discrete_log(base: int, target: int, modulus: int, order: int) -> int:
    """Return the unique exponent below ``order`` for this tiny cyclic group."""

    value = 1
    for exponent in range(order):
        if value == target:
            return exponent
        value = value * base % modulus
    raise AssertionError(f"{target} is not generated by {base} modulo {modulus}")


def theta_value(a: int) -> int:
    """The audited even primitive conductor-363 character modulo 23."""

    log3 = discrete_log(2, a % 3, 3, 2)
    log121 = discrete_log(2, a % 121, 121, 110)
    return pow(5, 11 * log3 + 13 * log121, P)


UNITS_363 = tuple(a for a in range(1, CONDUCTOR) if math.gcd(a, CONDUCTOR) == 1)
EPSILON_EXPONENT = {a: pow(theta_value(a), -1, P) for a in UNITS_363}


def trim(poly: list[int], modulus: int) -> list[int]:
    """Normalize a dense polynomial over ``Z/modulus``."""

    poly = [coefficient % modulus for coefficient in poly]
    while len(poly) > 1 and poly[-1] == 0:
        poly.pop()
    return poly


def dense_divmod_monic(
    numerator: list[int], denominator: list[int], modulus: int | None = None
) -> tuple[list[int], list[int]]:
    """Divide dense polynomials by a monic denominator."""

    out = numerator[:]
    quotient = [0] * max(1, len(out) - len(denominator) + 1)
    while out != [0] and len(out) >= len(denominator):
        coefficient = out[-1]
        shift = len(out) - len(denominator)
        quotient[shift] = coefficient
        for index, value in enumerate(denominator):
            out[index + shift] -= coefficient * value
            if modulus is not None:
                out[index + shift] %= modulus
        out = trim(out, modulus) if modulus is not None else _trim_integer(out)
    if modulus is not None:
        return trim(quotient, modulus), trim(out, modulus)
    return _trim_integer(quotient), _trim_integer(out)


def _trim_integer(poly: list[int]) -> list[int]:
    while len(poly) > 1 and poly[-1] == 0:
        poly.pop()
    return poly


def phi_363() -> list[int]:
    """Construct Phi_363 = Phi_121(X^3) / Phi_121(X) over Z."""

    phi121 = [0] * 111
    for index in range(11):
        phi121[11 * index] = 1
    numerator = [0] * 331
    for index in range(11):
        numerator[33 * index] = 1
    quotient, remainder = dense_divmod_monic(numerator, phi121)
    assert remainder == [0]
    assert len(quotient) - 1 == 220
    return quotient


def field_mul(
    left: tuple[int, ...], right: tuple[int, ...], modulus: int
) -> tuple[int, ...]:
    """Multiply modulo T^22 + 255 T^11 + 487 and ``modulus``."""

    coefficients = [0] * (2 * DEGREE - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            coefficients[i + j] = (coefficients[i + j] + a * b) % modulus
    for exponent in range(2 * DEGREE - 2, DEGREE - 1, -1):
        value = coefficients[exponent]
        coefficients[exponent] = 0
        coefficients[exponent - 11] = (
            coefficients[exponent - 11] - 255 * value
        ) % modulus
        coefficients[exponent - 22] = (
            coefficients[exponent - 22] - 487 * value
        ) % modulus
    return tuple(coefficients[:DEGREE])


def field_pow(base: tuple[int, ...], exponent: int, modulus: int) -> tuple[int, ...]:
    result = (1,) + (0,) * (DEGREE - 1)
    while exponent:
        if exponent & 1:
            result = field_mul(result, base, modulus)
        exponent >>= 1
        if exponent:
            base = field_mul(base, base, modulus)
    return result


def t_power(exponent: int, modulus: int) -> tuple[int, ...]:
    t = (0, 1) + (0,) * (DEGREE - 2)
    return field_pow(t, exponent, modulus)


def epsilon_local(modulus: int = P2) -> tuple[int, ...]:
    one = (1,) + (0,) * (DEGREE - 1)
    epsilon = one
    for a in UNITS_363:
        power = t_power(a, modulus)
        factor = tuple((one[i] - power[i]) % modulus for i in range(DEGREE))
        epsilon = field_mul(
            epsilon, field_pow(factor, EPSILON_EXPONENT[a], modulus), modulus
        )
    return epsilon


def poly_mod_prime(poly: list[int], modulus_poly: list[int], prime: int) -> list[int]:
    _, remainder = dense_divmod_monic(poly, modulus_poly, prime)
    return remainder


def poly_mul_prime(
    left: list[int], right: list[int], modulus_poly: list[int], prime: int
) -> list[int]:
    product = [0] * (len(left) + len(right) - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            product[i + j] = (product[i + j] + a * b) % prime
    return poly_mod_prime(product, modulus_poly, prime)


def poly_pow_prime(
    base: list[int], exponent: int, modulus_poly: list[int], prime: int
) -> list[int]:
    result = [1]
    while exponent:
        if exponent & 1:
            result = poly_mul_prime(result, base, modulus_poly, prime)
        exponent >>= 1
        if exponent:
            base = poly_mul_prime(base, base, modulus_poly, prime)
    return result


def poly_gcd_prime(left: list[int], right: list[int], prime: int) -> list[int]:
    left = trim(left, prime)
    right = trim(right, prime)
    while right != [0]:
        _, remainder = dense_divmod_monic_after_normalization(left, right, prime)
        left, right = right, remainder
    inverse = pow(left[-1], -1, prime)
    return trim([coefficient * inverse for coefficient in left], prime)


def dense_divmod_monic_after_normalization(
    numerator: list[int], denominator: list[int], prime: int
) -> tuple[list[int], list[int]]:
    inverse = pow(denominator[-1], -1, prime)
    monic = trim([coefficient * inverse for coefficient in denominator], prime)
    quotient, remainder = dense_divmod_monic(numerator, monic, prime)
    quotient = trim([coefficient * inverse for coefficient in quotient], prime)
    return quotient, remainder


def binary_mod(value: int, modulus: int) -> int:
    degree = modulus.bit_length() - 1
    while value.bit_length() - 1 >= degree:
        value ^= modulus << (value.bit_length() - 1 - degree)
    return value


def binary_mul(left: int, right: int, modulus: int) -> int:
    result = 0
    while right:
        if right & 1:
            result ^= left
        right >>= 1
        left <<= 1
        if left.bit_length() == modulus.bit_length():
            left ^= modulus
    return result


def binary_pow(base: int, exponent: int, modulus: int) -> int:
    result = 1
    while exponent:
        if exponent & 1:
            result = binary_mul(result, base, modulus)
        exponent >>= 1
        if exponent:
            base = binary_mul(base, base, modulus)
    return result


def binary_gcd(left: int, right: int) -> int:
    while right:
        left, right = right, binary_mod(left, right)
    return left


def main() -> None:
    assert len(UNITS_363) == 220
    assert pow(2, 110, 121) == 1 and pow(2, 55, 121) != 1
    assert theta_value(2) == 2
    assert theta_value(-1 % CONDUCTOR) == 1

    cyclotomic = phi_363()
    hensel = [487] + [0] * 10 + [255] + [0] * 10 + [1]
    _, hensel_remainder = dense_divmod_monic(cyclotomic, hensel, P2)
    assert hensel_remainder == [0]

    # Rabin irreducibility of T^22 + 2 T^11 + 4 over F_23.
    h1 = [4] + [0] * 10 + [2] + [0] * 10 + [1]
    x = [0, 1]
    assert poly_pow_prime(x, P**DEGREE, h1, P) == x
    for divisor in (2, 11):
        frobenius = poly_pow_prime(x, P ** (DEGREE // divisor), h1, P)
        difference = trim(
            [
                (frobenius[i] if i < len(frobenius) else 0)
                - (x[i] if i < len(x) else 0)
                for i in range(max(len(frobenius), len(x)))
            ],
            P,
        )
        assert poly_gcd_prime(h1, difference, P) == [1]

    local_epsilon = epsilon_local()
    expected_local = (
        344,
        186,
        101,
        283,
        348,
        493,
        134,
        197,
        425,
        138,
        469,
        424,
        133,
        435,
        387,
        355,
        122,
        446,
        153,
        13,
        122,
        226,
    )
    assert local_epsilon == expected_local
    residue_order = P**DEGREE - 1
    assert field_pow(local_epsilon, residue_order, P2) == ((1,) + (0,) * (DEGREE - 1))
    inverse_exponent = pow(P, -1, residue_order)
    assert inverse_exponent == 39_471_584_120_695_485_887_249_589_623
    local_root = field_pow(local_epsilon, inverse_exponent, P2)
    assert field_pow(local_root, P, P2) == local_epsilon

    # Exact residue at 2 in F_(2^110).
    binary_modulus = (1 << 110) | (1 << 33) | 1
    generator = 0b111
    binary_x = 0b10
    assert binary_pow(binary_x, 1 << 110, binary_modulus) == binary_x
    for divisor in (2, 5, 11):
        assert (
            binary_gcd(
                binary_modulus,
                binary_pow(binary_x, 1 << (110 // divisor), binary_modulus) ^ binary_x,
            )
            == 1
        )

    z = binary_pow(generator, ((1 << 110) - 1) // FULL_CONDUCTOR, binary_modulus)
    assert z == 0x31C5964EB9A0B194F731DE2284B9
    assert binary_pow(z, FULL_CONDUCTOR, binary_modulus) == 1
    for divisor in (3, 11, 23):
        assert binary_pow(z, FULL_CONDUCTOR // divisor, binary_modulus) != 1
    zeta363 = binary_pow(z, P, binary_modulus)
    zeta23 = binary_pow(z, CONDUCTOR, binary_modulus)

    epsilon = 1
    for a in UNITS_363:
        factor = binary_pow(zeta363, a, binary_modulus) ^ 1
        epsilon = binary_mul(
            epsilon,
            binary_pow(factor, EPSILON_EXPONENT[a], binary_modulus),
            binary_modulus,
        )
    assert epsilon == 0x533A83D1770BA6987ACD705100A
    phase = binary_pow(epsilon, ((1 << 110) - 1) // P, binary_modulus)
    assert phase == 0x230624CA45DA272928C1AB2181D1
    assert phase == binary_pow(zeta23, 4, binary_modulus)
    assert phase != 1 and binary_pow(phase, P, binary_modulus) == 1

    # In the descended degree-23 extension, Frob_Q = Frob_q^110.  Hence
    # the displayed exponent 4 corresponds to 4 / 110 = 13 modulo 23.
    assert (110 * 13) % P == 4

    print("ordinary p=23 marked Artin certificate: ok")
    print(f"local_epsilon={local_epsilon}")
    print(f"binary_epsilon={epsilon:#x}")
    print(f"phase={phase:#x}=zeta23^4")
    print("descended_frobenius_exponent=13")


if __name__ == "__main__":
    main()
