"""Row planner for engine v2 (crossed-binomial method).

For a prime p it decides whether a crossed-binomial path applies and emits the
program for ./v2engine:

  singleton  Q(h) = {R}, R = r^a odd (arms O, C, D): z = chi_R, z^R = alpha_r,
             targets z + m for every translate m = 0..rule.
  ratio      Q(h) = {R1, R2} odd prime powers (arm Z): beta = y1 + y2 =
             y2 (1 + z), z = y1/y2, z^(R1 R2) = alpha_r1^R2 / alpha_r2^R1,
             requires h not dividing d(y2) and [K(y1,y2):K] = R1 R2.
  finite     Q(h) = {2^k, R1} (arm Z): beta = y2 (1 + z), y2 = chi_{2^k},
             z^R1 = alpha_r1 / chi_{2^k}^R1.

The parent field K is generated by the radicands' closure (plus translates and
the finite component) in ONE synchronized model, so shared ancestors are the
same element.  Every structural condition is re-checked exactly by the engine.
"""
from __future__ import annotations

from math import gcd

import census2 as C
from census2 import d_finite, factor, factor_pp, lcm, ordtwo


def nimber_terms(m: int) -> list[list[int]]:
    """Finite nimber m as monomials, each a list of 2-power q's."""
    terms = []
    i = 0
    while m >> i:
        if (m >> i) & 1:
            mono = []
            j = 0
            while i >> j:
                if (i >> j) & 1:
                    mono.append(1 << (j + 1))
                j += 1
            terms.append(mono)
        i += 1
    return terms


class Closure:
    """Components in dependency order with their defining relations."""

    def __init__(self, excess: dict[int, int]):
        self.excess = excess
        self.order: list[int] = []
        self.rel: dict[int, tuple] = {}

    def alpha_expr(self, r: int) -> list[list[int]]:
        """Add the components of alpha_r = kappa_{f(r)} + m_r; return its expression."""
        hr = ordtwo(r)
        Q = C.Qset(hr)
        if self.excess is None:  # structural planning: assume the rule below p
            m_r = C.rule(r, hr, Q)
        elif r not in self.excess:
            raise Refuse(f"excess of closure prime {r} unknown")
        else:
            m_r = self.excess[r]
        if m_r != C.rule(r, hr, Q):
            raise Refuse(f"closure prime {r} has excess {m_r} != rule (not handled)")
        expr = [[qq] for qq in Q] + nimber_terms(m_r)
        for mono in expr:
            for qq in mono:
                self.add(qq)
        return expr

    def add(self, q: int) -> None:
        if q in self.rel:
            return
        r, k = factor_pp(q)
        if r == 2:
            for j in range(1, k):
                self.add(1 << j)
            self.rel[q] = ("AS", [[1 << j for j in range(1, k)]])
        elif k >= 2:
            self.add(q // r)
            self.rel[q] = ("K", r, [[q // r]])
        else:
            self.rel[q] = ("K", r, self.alpha_expr(r))
        self.order.append(q)

    def degree(self, q: int) -> int:
        r, _ = factor_pp(q)
        return q if r == 2 else C.dq(q)

    def lines(self) -> tuple[list[str], dict[int, int]]:
        idx = {q: i for i, q in enumerate(self.order)}
        out = [f"N {len(self.order)}"]
        for q in self.order:
            rel = self.rel[q]
            ell, expr = (2, rel[1]) if rel[0] == "AS" else (rel[1], rel[2])
            out.append(f"C {q} {ell} {self.degree(q)} {len(expr)} : {fmt(expr, idx)}")
        return out, idx


def fmt(expr, idx) -> str:
    return " ; ".join((" ".join(str(idx[x]) for x in mono) or "-") for mono in expr)


def vr(n: int, r: int) -> int:
    v = 0
    while n % r == 0:
        n //= r
        v += 1
    return v


class Refuse(Exception):
    pass


def plan(p: int, excess: dict[int, int] | None, t_mult: int = 1, ps: list[int] | None = None) -> dict:
    """Plan row p.  Returns a dict with 'program' (engine input) and parameters,
    or raises Refuse with the reason."""
    p, h, Q, arm, rule, E = C.row(p)
    cl = Closure(excess)
    radicand: list[tuple[int, list]] = []
    tests: list[tuple[int, list]] = []  # (label, k-constant expression)
    if arm in ("O", "C", "D"):
        R = Q[0]
        r, _ = factor_pp(R)
        alpha = cl.alpha_expr(r)
        translates = list(range(rule + 1))
        for m in translates:
            for mono in nimber_terms(m):
                for qq in mono:
                    cl.add(qq)
        B = lcm(C.b(r), max(d_finite(m) for m in translates))
        radicand = [(1, alpha)]
        tests = [(m, nimber_terms(m)) for m in translates]
        Rprimes = [r]
        dk = max(d_finite(m) for m in translates)
        path = "singleton"
        if E != R * B:
            raise Refuse(f"E={E} != R*B={R*B}")
    elif arm == "Z" and len(Q) == 2:
        odd = [q for q in Q if q % 2 == 1]
        two = [q for q in Q if q % 2 == 0]
        if len(odd) == 2:
            dy = {q: C.dq(q) for q in Q}
            dens = [q for q in Q if dy[q] % h != 0]
            if not dens:
                raise Refuse("both components have degree divisible by h")
            R2 = dens[0]  # denominator y2: h does not divide d(y2)
            R1 = [q for q in Q if q != R2][0]
            r1, _ = factor_pp(R1)
            r2, _ = factor_pp(R2)
            a1 = cl.alpha_expr(r1)
            a2 = cl.alpha_expr(r2)
            B = lcm(C.b(r1), C.b(r2))
            R = R1 * R2
            if E != R * B:
                raise Refuse(f"inherited level: E={E} != R1 R2 B={R*B}")
            radicand = [(R2, a1), (-R1, a2)]
            Rprimes = sorted([r1, r2])
            path = "ratio"
        elif len(odd) == 1 and len(two) == 1:
            R1, Y2 = odd[0], two[0]
            r1, _ = factor_pp(R1)
            a1 = cl.alpha_expr(r1)
            cl.add(Y2)
            B = lcm(C.b(r1), Y2)
            R = R1
            if E != R * B:
                raise Refuse(f"E={E} != R*B={R*B}")
            radicand = [(1, a1), (-R1, [[Y2]])]
            Rprimes = [r1]
            path = "finite"
        else:
            raise Refuse(f"Z row shape {Q}")
        tests = [(0, nimber_terms(1))]  # beta p-th power  <=>  1 + z p-th power
        dk = 1
    else:
        raise Refuse(f"arm {arm} with Q={Q} not handled")

    t0 = h // gcd(h, R)
    t0 = lcm(t0, dk)
    for l in Rprimes:
        t0 = lcm(t0, ordtwo(l))
        t0 = lcm(t0, l ** vr(B, l))
    if B % t0:
        raise Refuse(f"cut t0={t0} does not divide B={B}")
    t = t0 * t_mult
    if B % t or gcd(B // t, R) != 1:
        raise Refuse(f"t={t} not admissible")
    D = B // t
    lines = [f"B {B}", f"H {h}", f"R {R} {len(Rprimes)} " + " ".join(map(str, Rprimes)), f"T {t}"]
    cl_lines, idx = cl.lines()
    lines += cl_lines
    for e, ex in radicand:
        lines.append(f"A {e} {len(ex)} : {fmt(ex, idx)}")
    for lab, ex in tests:
        lines.append(f"M {lab} {len(ex)} : {fmt(ex, idx)}")
    ps = ps or [p]
    lines.append(f"PS {len(ps)} " + " ".join(map(str, ps)))
    return {
        "p": p, "h": h, "Q": list(Q), "arm": arm, "rule": rule, "E": E, "path": path,
        "B": B, "R": R, "t": t, "D": D, "Rt": R * t, "ncomp": len(cl.order),
        "program": "\n".join(lines) + "\n",
    }


def ref_program(p: int, excess: dict[int, int] | None, translates: list[int]) -> str:
    """Program for the reference engine (one model of degree E), as ../ref/rowprog.py."""
    h = ordtwo(p)
    Q = C.Qset(h)
    cl = Closure(excess)
    for q in Q:
        cl.add(q)
    E = C.dsum(Q)
    for m in translates:
        for mono in nimber_terms(m):
            for qq in mono:
                cl.add(qq)
        E = lcm(E, d_finite(m))
    cl_lines, idx = cl.lines()
    out = [f"E {E}", f"P {p}"] + cl_lines
    out.append(f"T {len(Q)} : " + " ; ".join(str(idx[q]) for q in Q))
    for m in translates:
        mt = nimber_terms(m)
        out.append(f"M {m} {len(mt)} : {fmt(mt, idx)}")
    return "\n".join(out) + "\n"


def closure_primes(p: int) -> set[int]:
    """Odd primes r whose alpha_r enters row p (all ancestors)."""
    out: set[int] = set()
    stack = [p]
    while stack:
        x = stack.pop()
        for q in C.Qset(ordtwo(x)):
            r, _ = factor_pp(q)
            if r > 2 and r not in out:
                out.add(r)
                stack.append(r)
    return out


if __name__ == "__main__":
    import sys

    p = int(sys.argv[1])
    exc = {r: C.rule(r, ordtwo(r), C.Qset(ordtwo(r))) for r in closure_primes(p)}
    d = plan(p, exc)
    sys.stdout.write(d["program"])
    print({k: v for k, v in d.items() if k != "program"}, file=sys.stderr)
