#include <NTL/GF2X.h>
#include <NTL/GF2XFactoring.h>
#include <NTL/GF2EX.h>
#include <NTL/vec_GF2.h>
#include <chrono>
#include <iostream>
using namespace NTL; using namespace std;
double now(){return chrono::duration<double>(chrono::steady_clock::now().time_since_epoch()).count();}
template<class F> double timeit(F f, double minT=0.3){ int reps=0; double t0=now(), t; do { f(); reps++; t=now()-t0; } while(t<minT); return t/reps; }
// Taylor shift by 1 on a GF2X in place via word masks: f(X) -> f(X+1)
void taylor1(GF2X& f, long n){ // n = number of coefficients (power of two not required)
  f.xrep.SetLength((n+63)/64); _ntl_ulong* w=f.xrep.elts(); long W=f.xrep.length();
  static const _ntl_ulong M[6]={0x5555555555555555UL,0x3333333333333333UL,0x0F0F0F0F0F0F0F0FUL,0x00FF00FF00FF00FFUL,0x0000FFFF0000FFFFUL,0x00000000FFFFFFFFUL};
  for(int k=0;k<6;k++){ int s=1<<k; for(long i=0;i<W;i++) w[i]^=(w[i]>>s)&M[k]; }
  for(long s=1; s<W; s<<=1) for(long i=0;i<W;i++) if(i & s) w[i^s]^=w[i];
  f.normalize();
}
int main(){
  cout.precision(4);
  cout<<"== plain GF2X mul, sqr, taylor-shift (ms)\n";
  for(long n: {10000L,100000L,1000000L,10000000L,30000000L}){
    GF2X a,b,c; random(a,n); random(b,n);
    double tm=timeit([&]{ mul(c,a,b); });
    double ts=timeit([&]{ sqr(c,a); });
    GF2X f=a; double tt=timeit([&]{ taylor1(f,n); });
    cout<<"n="<<n<<" mul="<<tm*1e3<<" sqr="<<ts*1e3<<" taylor1="<<tt*1e3<<endl;
  }
  // verify taylor shift on small random poly: f(X+1) == compose
  { GF2X f; random(f,1000); GF2X g=f; taylor1(g,1000); GF2X x1; SetX(x1); x1+=1; GF2X h; // Horner
    for(long i=deg(f);i>=0;i--){ h*=x1; if(IsOne(coeff(f,i))) h+=1; }
    cout<<"taylor1 check: "<<(g==h)<<endl; }
  cout<<"== MinPolySeq over GF2 (length 2n) (s)\n";
  for(long n: {10000L,100000L,1000000L}){
    GF2X P; BuildSparseIrred(P,n); GF2XModulus F(P);
    // sequence: constant coeff of x^i  -> generated by P
    vec_GF2 s; s.SetLength(2*n);
    GF2X x; set(x); GF2X X; SetX(X);
    // fast generation: s_i = coeff of X^{n-1} in X^i mod P is the impulse response: use series inverse
    GF2X rP; reverse(rP,P,n); GF2X inv; InvTrunc(inv,rP,2*n);
    for(long i=0;i<2*n;i++){ long t=i-(n-1); s[i]= t>=0? coeff(inv,t):GF2(0);} 
    GF2X h; double t=timeit([&]{ MinPolySeq(h,s,n); },0.1);
    cout<<"n="<<n<<" MinPolySeq="<<t<<" ok="<<(h==P)<<endl;
  }
  cout<<"== GF2EX mul over K=GF(2^d) with total bits E (ms) vs GF2X mul of E bits\n";
  for(long d: {2L,4L,12L,20L,60L,220L}){
    GF2X PK; BuildIrred(PK,d); GF2E::init(PK);
    for(long E: {100000L,1000000L}){
      long D=E/d; GF2EX a,b,c; random(a,D); random(b,D);
      double tm=timeit([&]{ mul(c,a,b); });
      GF2EX G; random(G,D); SetCoeff(G,D); GF2EXModulus FG(G);
      double tmm=timeit([&]{ MulMod(c,a,b,FG); });
      cout<<"d="<<d<<" E="<<E<<" D="<<D<<" mul="<<tm*1e3<<" mulmod="<<tmm*1e3<<endl;
    }
  }
  cout<<"== MinPolySeq over GF2E length 2D (s)\n";
  for(long d: {4L,12L}){
    GF2X PK; BuildIrred(PK,d); GF2E::init(PK);
    for(long D: {10000L,100000L}){
      GF2EX G; random(G,D); SetCoeff(G,D);
      GF2EX rG; reverse(rG,G,D); GF2EX inv; InvTrunc(inv,rG,2*D);
      vec_GF2E s; s.SetLength(2*D); for(long i=0;i<2*D;i++){ long t=i-(D-1); if(t>=0) s[i]=coeff(inv,t); }
      GF2EX h; double t=timeit([&]{ MinPolySeq(h,s,D); },0.1);
      cout<<"d="<<d<<" D="<<D<<" MinPolySeq="<<t<<" ok="<<(h==G)<<endl;
    }
  }
}
